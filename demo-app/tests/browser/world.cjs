const { chromium } = require('playwright')
const OUT = process.env.SHOTS || '/tmp/doorlink-shots'
const mobile = process.argv.includes('--mobile')
const BASE = process.env.XURL || 'http://localhost:4300/'
;(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
  const page = await browser.newPage(mobile ? { viewport: { width: 430, height: 932 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true } : { viewport: { width: 1280, height: 760 } })
  await page.addInitScript(() => { try { localStorage.setItem('doorlink:intro-seen-v1', '1') } catch {} })
  const errs = []
  page.on('pageerror', (e) => errs.push('pageerror: ' + e.message))
  page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text().slice(0, 200)) })
  const p = mobile ? 'm-' : ''
  let fails = 0
  const shot = (n) => page.screenshot({ path: `${OUT}/${p}w${n}.png` })
  const home = async () => { await page.getByRole('button', { name: 'Reset view' }).click(); await page.waitForTimeout(2500) }
  const step = async (name, fn) => { try { await fn(); console.log('OK  ', name) } catch (e) { fails++; console.log('FAIL', name, e.message.split('\n')[0]); await page.screenshot({ path: `${OUT}/${p}wfail-${name.replace(/\W+/g, '-')}.png` }) } }
  const caption = (t, timeout = 60000) => page.locator('.world-caption', { hasText: t }).waitFor({ timeout })
  await page.goto(BASE + '#/')
  await page.evaluate(() => sessionStorage.clear()); await page.reload()
  await step('open garage, invite offers Doorlink World', async () => {
    await page.getByRole('button', { name: /OPEN THE DOOR/ }).click()
    await page.getByRole('button', { name: 'Enter Doorlink World' }).waitFor({ timeout: 15000 })
    await shot('0-invite')
  })
  await step('world loads', async () => {
    await page.getByRole('button', { name: 'Enter Doorlink World' }).click()
    await page.locator('.world-root canvas').waitFor({ timeout: 30000 })
    await page.waitForFunction(() => !document.querySelector('.world-root .xray-loading'), null, { timeout: 120000 })
    await page.waitForTimeout(5000)
    await shot('1-before')
  })
  await step('transformation runs through its steps', async () => {
    await page.evaluate(() => { window.__seen = []; new MutationObserver(() => { const t = document.querySelector('.world-caption p')?.textContent; if (t && window.__seen.at(-1) !== t) window.__seen.push(t) }).observe(document.querySelector('.world-bottom'), { subtree: true, childList: true, characterData: true }) })
    await page.getByRole('button', { name: 'Transform my property' }).click()
    await caption('Your upgraded property', 60000)
    const seen = await page.evaluate(() => window.__seen)
    console.log('     captions:', seen.length, seen.map((t) => t.slice(0, 28)).join(' | '))
    for (const want of ['garage door', 'sliding gate', 'slat fence', 'roller shutters', 'working together']) if (!seen.some((t) => t.includes(want))) throw new Error('missing step ' + want)
    await page.waitForTimeout(14000); await shot('6-after')
  })
  await step('tap sliding gate: it operates, card and x-ray', async () => {
    await home()
    await page.getByRole('button', { name: 'Operate the sliding gate' }).click()
    await page.locator('.world-card', { hasText: 'Automated sliding gate' }).waitFor()
    await page.waitForTimeout(5000); await shot('7-gate-closed')
    await page.locator('.world-card').getByRole('button', { name: 'X-ray' }).click()
    await page.waitForTimeout(4000); await shot('8-gate-xray')
  })
  await step('fence styles', async () => {
    await home()
    await page.getByRole('button', { name: 'Operate the fencing' }).click({ force: true })
    await page.getByRole('button', { name: /Timber-look slats/ }).click()
    await page.waitForTimeout(4000); await shot('9-fence-timber')
  })
  await step('shutters x-ray', async () => {
    await home()
    await page.getByRole('button', { name: 'Operate the roller shutters' }).click()
    await page.waitForTimeout(9000); await shot('10a-shutters')
    await page.locator('.world-card').getByRole('button', { name: 'X-ray' }).click()
    await page.waitForTimeout(4000); await shot('10-shutters-xray')
  })
  await step('night mode closes up the property', async () => {
    await page.getByRole('button', { name: /night/i }).click()
    await page.getByRole('button', { name: 'Reset view' }).click()
    await page.waitForTimeout(12000); await shot('11-night')
    await page.getByRole('button', { name: /to day/i }).click()
  })
  await step('garage full x-ray opens and returns', async () => {
    await home()
    await page.getByRole('button', { name: 'Operate the garage door' }).click()
    await page.getByRole('button', { name: 'Full X-ray garage' }).click()
    await page.waitForFunction(() => document.querySelector('.xray-root canvas') && !document.querySelector('.xray-root .xray-loading'), null, { timeout: 90000 })
    await page.getByRole('button', { name: 'Exit X-ray' }).click()
    await page.waitForTimeout(800)
    if (!(await page.locator('.world-root').count())) throw new Error('world closed too')
  })
  await step('camera stays bounded after hard drag and zoom', async () => {
    await page.getByRole('button', { name: 'Reset view' }).click()
    await page.waitForTimeout(2000)
    const b = await page.locator('.world-root canvas').boundingBox()
    await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2); await page.mouse.down()
    for (let i = 1; i <= 10; i++) await page.mouse.move(b.x + b.width / 2 - i * 60, b.y + b.height / 2 - i * 30)
    await page.mouse.up()
    for (let i = 0; i < 20; i++) await page.mouse.wheel(0, -500)
    await page.waitForTimeout(3000); await shot('12-dragged')
  })
  await step('replay then skip', async () => {
    await page.getByRole('button', { name: 'Replay the transformation' }).click()
    await caption('Back to the original', 5000)
    await caption('garage door', 20000)
    await page.getByRole('button', { name: 'Skip to the finished property' }).click()
    await caption('Your upgraded property', 5000)
  })
  await step('exit returns to the homepage', async () => {
    await page.getByRole('button', { name: 'Exit', exact: true }).click()
    await page.waitForTimeout(500)
    if (await page.locator('.world-root').count()) throw new Error('still open')
    if (!(await page.getByRole('button', { name: /CLOSE THE DOOR/ }).count())) throw new Error('hero missing')
    if ((await page.evaluate(() => document.body.style.overflow)) === 'hidden') throw new Error('scroll locked')
  })
  console.log(errs.length ? errs.join('\n') : 'no errors')
  console.log(fails ? `${fails} FAILED` : 'WORLD OK')
  await browser.close()
})()
